/**
 * Returns festivals that match or overlap the traveler's month and/or destination.
 */
export function getOverlappingFestivals(travelMonth = 'October', destination = '') {
  const monthLower = (travelMonth || '').toLowerCase().trim()
  const destLower = (destination || '').toLowerCase().trim()

  const directMatches = []
  const monthMatches = []

  KARNATAKA_FESTIVALS.forEach((fest) => {
    const isMonthMatch = fest.approxMonths.some((m) => monthLower.includes(m))
    const isDestMatch =
      destLower.length > 2 &&
      (fest.destination.toLowerCase().includes(destLower) ||
        destLower.includes(fest.destination.toLowerCase()))

    if (isMonthMatch && isDestMatch) {
      directMatches.push({ ...fest, matchType: 'perfect' })
    } else if (isMonthMatch) {
      monthMatches.push({ ...fest, matchType: 'month' })
    }
  })

  // Return direct matches first, followed by general month events
  return [...directMatches, ...monthMatches]
}
