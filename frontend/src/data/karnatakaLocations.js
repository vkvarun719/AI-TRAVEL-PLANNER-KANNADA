/**
 * Searches the location catalog by text query matching English, Kannada, aliases, or district.
 */
export function searchKarnatakaLocations(query = '', categoryFilter = 'all') {
  const q = (query || '').trim().toLowerCase()

  return KARNATAKA_LOCATIONS.filter(loc => {
    // 1. Category filter
    if (categoryFilter !== 'all' && loc.category !== categoryFilter) {
      return false
    }

    if (!q) return true

    // 2. Search match
    const valMatch = loc.value.toLowerCase().includes(q)
    const enMatch = loc.en.toLowerCase().includes(q)
    const knMatch = loc.kn.includes(query)
    const distMatch = loc.district?.toLowerCase().includes(q)
    const aliasMatch = loc.aliases?.some(a => a.toLowerCase().includes(q))
    const highlightMatch = loc.highlightEn?.toLowerCase().includes(q) || loc.highlightKn?.includes(query)

    return valMatch || enMatch || knMatch || distMatch || aliasMatch || highlightMatch
  })
}

/**
 * Returns a normalized location record or synthesizes one for any custom place name typed.
 */
export function resolveLocation(placeName = 'Bangalore') {
  if (!placeName) return KARNATAKA_LOCATIONS[0]

  const clean = placeName.trim().toLowerCase()
  const found = KARNATAKA_LOCATIONS.find(loc => {
    if (loc.value.toLowerCase() === clean) return true
    if (loc.aliases?.some(a => a.toLowerCase() === clean)) return true
    if (loc.en.toLowerCase().includes(clean)) return true
    if (loc.kn.includes(placeName)) return true
    return false
  })

  if (found) return found

  // Synthesize custom Karnataka location
  return {
    value: placeName.trim(),
    en: placeName.trim(),
    kn: placeName.trim(),
    district: 'Karnataka',
    category: 'custom',
    lat: 13.5, // approximate center of Karnataka
    lng: 75.8,
    highlightEn: `Custom travel destination in Karnataka: ${placeName}`,
    highlightKn: `ಕರ್ನಾಟಕದ ಸ್ಥಳ: ${placeName}`,
    isCustom: true
  }
}
